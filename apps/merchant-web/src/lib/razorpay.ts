/**
 * Fetches order details from the Razorpay API to verify status and amount.
 */
export async function fetchRazorpayOrder(orderId: string): Promise<RazorpayOrderDetails | null> {
  if (!orderId || !orderId.trim()) return null;

  // 1. Mock order response ONLY if explicitly enabled AND the order was created in mock mode
  if (canMockPayments() && (orderId.startsWith('order_mock_') || orderId.startsWith('mock_'))) {
    if (
      orderId.includes('invalid') ||
      orderId.includes('fake') ||
      orderId.includes('nonexistent')
    ) {
      return null;
    }
    if (orderId.includes('tampered')) {
      return {
        id: orderId,
        amount: 100, // 1 INR tampered amount (mismatched with booking deposit/total)
        currency: 'INR',
        status: 'created',
        is_mock: true,
      };
    }
    const mockAmountMatch = orderId.match(/^order_mock_(\d+)_/);
    const mockAmount = mockAmountMatch ? parseInt(mockAmountMatch[1], 10) : 11000;
    return {
      id: orderId,
      amount: mockAmount,
      currency: 'INR',
      status: 'created',
      is_mock: true,
    };
  }

  // 2. Query live Razorpay REST API when credentials are configured
  if (isRazorpayConfigured()) {
    try {
      const keyId = process.env.RAZORPAY_KEY_ID!;
      const keySecret = process.env.RAZORPAY_KEY_SECRET!;
      const authHeader = 'Basic ' + Buffer.from(`${keyId}:${keySecret}`).toString('base64');
      const res = await fetch(`https://api.razorpay.com/v1/orders/${encodeURIComponent(orderId)}`, {
        method: 'GET',
        headers: {
          Authorization: authHeader,
          'Content-Type': 'application/json',
        },
      });
      if (!res.ok) {
        return null;
      }
      const data = await res.json();
      return {
        id: data.id,
        amount: data.amount,
        amount_paid: data.amount_paid,
        currency: data.currency,
        receipt: data.receipt,
        status: data.status,
        notes: data.notes,
        is_mock: false,
      };
    } catch (err) {
      console.error('[Razorpay] fetch order failed:', err);
      return null;
    }
  }

  return null;
}

/**
 * Initiates a refund for a payment via Razorpay.
 */
export async function initiateRazorpayRefund(params: RefundParams): Promise<RazorpayRefundResult> {
  const { paymentId, amount, notes } = params;

  // Simulated failure hook for test runs (strictly non-production)
  if (canMockPayments() && (paymentId.includes('fail') || paymentId.includes('error'))) {
    throw new Error('Simulated Razorpay refund gateway failure');
  }

  const isSyntheticMock =
    canMockPayments() &&
    (paymentId.startsWith('sim_') ||
      paymentId.startsWith('mock_') ||
      paymentId.startsWith('pay_'));

  if (isRazorpayConfigured() && !isSyntheticMock) {
    const keyId = process.env.RAZORPAY_KEY_ID!;
    const keySecret = process.env.RAZORPAY_KEY_SECRET!;
    const authHeader = 'Basic ' + Buffer.from(`${keyId}:${keySecret}`).toString('base64');
    const res = await fetch(`https://api.razorpay.com/v1/payments/${paymentId}/refund`, {
      method: 'POST',
      headers: {
        Authorization: authHeader,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({
        ...(amount ? { amount } : {}),
        ...(notes ? { notes } : {}),
      }),
    });

    if (!res.ok) {
      const errData = await res.json().catch(() => ({}));
      throw new Error(errData?.error?.description || `Razorpay refund failed (status ${res.status})`);
    }

    const data = await res.json();
    return {
      id: data.id,
      amount: data.amount,
      status: data.status,
      is_mock: false,
    };
  }

  if (canMockPayments()) {
    return {
      id: `rfnd_mock_${Date.now().toString(36)}`,
      amount: amount || 0,
      status: 'processed',
      is_mock: true,
    };
  }

  throw new Error('Razorpay credentials are not configured and mock refunds are disabled.');
}
