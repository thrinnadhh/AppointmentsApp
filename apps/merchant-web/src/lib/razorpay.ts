/**
 * Fetches payment details from the Razorpay API to verify status and order linkage.
 */
export async function fetchRazorpayPayment(paymentId: string): Promise<RazorpayPaymentDetails | null> {
  if (!paymentId || !paymentId.trim()) return null;

  // 1. Mock payment response ONLY if explicitly enabled AND strictly in non-production
  if (canMockPayments()) {
    // Explicit failure simulation — always return null regardless of config
    if (
      paymentId.includes('fake') ||
      paymentId.includes('invalid') ||
      paymentId.includes('unverified') ||
      paymentId.includes('tampered') ||
      paymentId.includes('nonexistent') ||
      paymentId.includes('fail')
    ) {
      return null;
    }
    // When mock payments are enabled (test/dev), any synthetic payment ID
    // (sim_, mock_, pay_) gets a captured mock response instead of hitting live Razorpay.
    if (
      paymentId.startsWith('sim_') ||
      paymentId.startsWith('mock_') ||
      paymentId.startsWith('pay_mock_') ||
      paymentId.startsWith('pay_test_')
    ) {
      return {
        id: paymentId,
        status: 'captured',
        order_id: 'order_test_mock',
        amount: 11000,
        currency: 'INR',
      };
    }
  }

  // 2. Query live Razorpay REST API when credentials are configured
  if (isRazorpayConfigured()) {
    try {
      const keyId = process.env.RAZORPAY_KEY_ID!;
      const keySecret = process.env.RAZORPAY_KEY_SECRET!;
      const authHeader = 'Basic ' + Buffer.from(`${keyId}:${keySecret}`).toString('base64');
      const res = await fetch(`https://api.razorpay.com/v1/payments/${encodeURIComponent(paymentId)}`, {
        method: 'GET',
        headers: {
          Authorization: authHeader,
          'Content-Type': 'application/json',
        },
        signal: AbortSignal.timeout(10000),
      });
      if (!res.ok) {
        return null;
      }
      const data = await res.json();
      return {
        id: data.id,
        status: data.status,
        order_id: data.order_id,
        amount: data.amount,
        currency: data.currency,
      };
    } catch (err) {
      console.error('[Razorpay] fetch payment failed:', err);
      return null;
    }
  }

  return null;
}

